// Security regression tests for owner trusted-device sessions.
import assert from "node:assert/strict";
import { webcrypto } from "node:crypto";
import { onRequest } from "../functions/api/[[path]].js";
globalThis.crypto ||= webcrypto;

const token="s".repeat(64), env={STAR_API_TOKEN:token};
const root="https://star-cyber-ai-x.pages.dev";
const call=(path,options={},customEnv=env)=>onRequest({request:new Request(root+path,options),env:customEnv});
const json=async response=>({status:response.status,data:await response.json(),cookie:response.headers.get("set-cookie")||""});
const authHeaders={"Authorization":"Bearer "+token,"Origin":root};
let x=await json(await call("/api/auth/session"));
assert.equal(x.status,401,"Session is private by default");
x=await json(await call("/api/auth/remember",{method:"POST"}));
assert.equal(x.status,401,"Remember must refuse unauthenticated caller");
x=await json(await call("/api/auth/remember",{method:"POST",headers:{"Authorization":"Bearer wrong","Origin":root}}));
assert.equal(x.status,401,"Wrong token must fail");
x=await json(await call("/api/auth/remember",{method:"POST",headers:authHeaders}));
assert.equal(x.status,200,"Valid owner token creates session");
assert.equal(x.data.authenticated,true);
assert.match(x.cookie,/__Host-star_owner=/);
assert.match(x.cookie,/HttpOnly/);
assert.match(x.cookie,/Secure/);
assert.match(x.cookie,/SameSite=Strict/);
assert.match(x.cookie,/Max-Age=7776000/);
assert.doesNotMatch(x.cookie,new RegExp(token),"Cookie must not reveal API token");
const cookie=x.cookie.split(";")[0];
x=await json(await call("/api/auth/session",{headers:{"Cookie":cookie,"Sec-Fetch-Site":"same-origin"}}));
assert.equal(x.status,200,"Cookie should authenticate after browser restart");
assert.equal(x.data.method,"cookie");
const tampered=cookie.replace(/.$/,"x");
x=await json(await call("/api/auth/session",{headers:{"Cookie":tampered}}));
assert.equal(x.status,401,"Tampering invalidates signature");
x=await json(await call("/api/auth/session",{headers:{"Cookie":cookie}}, {STAR_API_TOKEN:"v".repeat(64)}));
assert.equal(x.status,401,"Rotating the server secret must revoke old cookies");
x=await json(await call("/api/chat",{method:"POST",headers:{"Cookie":cookie,"Origin":root,"Content-Type":"application/json"},body:JSON.stringify({prompt:"test"})}));
assert.equal(x.status,503,"Cookie authentication passes owner check, provider remains protected");
x=await json(await call("/api/chat",{method:"POST",headers:{"Cookie":cookie,"Sec-Fetch-Site":"cross-site","Content-Type":"application/json"},body:JSON.stringify({prompt:"test"})}));
assert.equal(x.status,401,"Cross-site requests may not use owner cookies");
x=await json(await call("/api/chat",{method:"POST",headers:{"Cookie":cookie,"Origin":"https://evil.example","Content-Type":"application/json"},body:JSON.stringify({prompt:"test"})}));
assert.equal(x.status,403,"Origin mismatch is forbidden");
x=await json(await call("/api/auth/logout",{method:"POST",headers:{"Cookie":cookie,"Origin":root}}));
assert.equal(x.status,200,"Owner may forget trusted device");
assert.match(x.cookie,/Max-Age=0/);
console.log("Owner persistent-session tests passed (signed cookie, no plaintext token, expiry, tampering, origin, rotation, logout)");
